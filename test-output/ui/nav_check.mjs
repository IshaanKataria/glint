import { _electron as electron } from '/Users/katana/experiments/cluely-clone/node_modules/@playwright/test/index.mjs';
const root = '/Users/katana/experiments/cluely-clone';
const app = await electron.launch({ args: [root], cwd: root, env: { ...process.env, GLINT_TEST: '1', GLINT_DATA_DIR: root + '/test-output/ui-data' } });
const out = [];
const check = (label, cond, extra = '') => out.push(`${cond ? 'PASS' : 'FAIL'}  ${label}${extra ? '  ' + extra : ''}`);
try {
  const ov = await app.firstWindow();
  await ov.waitForFunction(() => !!window.glint);
  const [dash] = await Promise.all([app.waitForEvent('window'), ov.evaluate(() => window.glint.app.openDashboard({ view: 'history' }))]);
  await dash.waitForFunction(() => !!window.glint);
  await dash.goto(dash.url().split('?')[0] + '?fixture=history');
  await dash.waitForSelector('.note > *');
  const sel = () => dash.evaluate(() => document.querySelector('.row.sel .row-title')?.textContent);
  const title = () => dash.evaluate(() => document.querySelector('.note-title')?.textContent);
  const tab = () => dash.evaluate(() => document.querySelector('.seg button.on')?.textContent);
  const backDisabled = () => dash.evaluate(() => document.querySelector('#back').disabled);
  const first = await title();
  check('back disabled at start', await backDisabled());
  await dash.click('.row:nth-of-type(3)'); await dash.waitForTimeout(300);
  const second = await title();
  check('clicking another row changes the note', second !== first, `"${first}" -> "${second}"`);
  check('back enabled after moving', !(await backDisabled()));
  await dash.click('.seg button:nth-child(2)'); await dash.waitForTimeout(200);
  check('tab switched to Transcript', (await tab()) === 'Transcript');
  await dash.click('#back'); await dash.waitForTimeout(300);
  check('back #1 returns to Summary on the same note', (await tab()) === 'Summary' && (await title()) === second);
  await dash.click('#back'); await dash.waitForTimeout(400);
  check('back #2 returns to the first note', (await title()) === first && (await sel()) !== null, `"${await title()}"`);
  check('back disabled again', await backDisabled());
  await dash.click('#open-settings'); await dash.waitForTimeout(200);
  check('back enabled while Settings is open', !(await backDisabled()));
  await dash.click('#back'); await dash.waitForTimeout(200);
  check('back closes Settings', await dash.evaluate(() => document.querySelector('#settings').hidden));
  await dash.keyboard.press('Meta+K');
  check('⌘K focuses search', await dash.evaluate(() => document.activeElement?.id === 'search'));
  await dash.keyboard.type('budget');
  await dash.keyboard.press('Enter'); await dash.waitForTimeout(400);
  check('Enter opens the first match', /budget/i.test(await title()), `"${await title()}"`);
  await dash.fill('#search', 'roadmap');
  await dash.click('#search-go'); await dash.waitForTimeout(400);
  check('↗ button opens the first match', /roadmap/i.test(await title()), `"${await title()}"`);
  await dash.keyboard.press('Meta+BracketLeft'); await dash.waitForTimeout(400);
  check('⌘[ goes back', /budget/i.test(await title()), `"${await title()}"`);
} finally { await app.close(); }
console.log(out.join('\n'));
